"""Validate the server catalogs and emit immutable C++ lookup tables."""

import json
import sys
from pathlib import Path
from string import Formatter


def unique_entries(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate locale key: {key}")
        if not isinstance(value, str):
            raise ValueError(f"Message for {key} must be a string")
        result[key] = value
    return result


def read_catalog(path):
    messages = json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=unique_entries)
    if not isinstance(messages, dict):
        raise ValueError(f"{path} must contain a JSON object")
    return messages


def fields(message):
    return [(field, spec, conversion)
            for _, field, spec, conversion in Formatter().parse(message)
            if field is not None]


def generate(source, output):
    en = read_catalog(source / "en.json")
    es = read_catalog(source / "es.json")
    if en.keys() != es.keys():
        raise ValueError(f"Catalog keys differ: {sorted(en.keys() ^ es.keys())}")
    for key in en:
        if fields(en[key]) != fields(es[key]):
            raise ValueError(f"Format fields differ for {key}")

    lines = ["// Generated by generate-i18n-data.py", "#pragma once", "",
             "#include <array>", "#include <string_view>", "#include <utility>", "",
             "namespace angel_lsp::i18n", "{"]
    for locale, messages in (("en", en), ("es", es)):
        lines.append(f"inline constexpr std::array<std::pair<std::string_view, std::string_view>, "
                     f"{len(messages)}> k_{locale}Messages = {{{{")
        for key, value in sorted(messages.items()):
            lines.append("    {" + json.dumps(key, ensure_ascii=False) + ", " +
                         json.dumps(value, ensure_ascii=False) + "},")
        lines.append("}};")
    lines.extend(["}", ""])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    generate(Path(sys.argv[1]), Path(sys.argv[2]))
